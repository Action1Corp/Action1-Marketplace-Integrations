async function checkConfiguration(context, { settings }) {
  const apiUrl = settings?.HelloApiUrl || await context.settings.get('HelloApiUrl');
  const hasUrl = typeof apiUrl === 'string' && apiUrl.trim().length > 0;

  return {
    ok: hasUrl,
    message: hasUrl
      ? 'Custom action completed. The API URL is available to this integration.'
      : 'Custom action failed. Configure the API URL before running this action.'
  };
}

async function inspectSettings(context, { settings, payload }) {
  const apiUrl = settings?.HelloApiUrl || await context.settings.get('HelloApiUrl');
  const tokenValue = settings?.HelloApiToken || '';
  const tokenProvided = tokenValue && tokenValue !== '***';

  return {
    ok: true,
    message: 'Settings were inspected without exposing secret values.',
    details: {
      screen: payload?.screen || 'unknown',
      apiUrl: apiUrl || 'not configured',
      apiToken: tokenProvided ? 'provided in request' : 'stored or not provided',
      integrationId: context.integrationId
    }
  };
}

async function generateSummary() {
  return {
    ok: true,
    message: 'Example summary generated by the integration.',
    details: {
      status: 'Ready',
      itemsReviewed: 3,
      nextRecommendedStep: 'Use this pattern for vendor-specific operations that do not fit the standard run flow.'
    },
    data: [
      { label: 'Custom screens', value: 'Rendered by integration React views' },
      { label: 'Custom buttons', value: 'Declared in manifest.json actions' },
      { label: 'Custom behavior', value: 'Implemented in actions.js' }
    ]
  };
}

async function runtimeDiagnostics(context) {
  const endpointTable = context.db.tables.endpoints;
  const cveTable = context.db.tables.endpointCves;
  const endpointRow = await context.db.get(`SELECT COUNT(*) AS count FROM ${endpointTable}`);
  const cveRow = await context.db.get(`SELECT COUNT(*) AS count FROM ${cveTable}`);

  return {
    ok: true,
    message: 'Runtime diagnostics completed.',
    details: {
      integrationId: context.integrationId,
      endpointTable,
      endpointRows: endpointRow?.count || 0,
      vulnerabilityTable: cveTable,
      vulnerabilityRows: cveRow?.count || 0
    }
  };
}

module.exports = {
  actions: {
    'check-configuration': checkConfiguration,
    'inspect-settings': inspectSettings,
    'generate-summary': generateSummary,
    'runtime-diagnostics': runtimeDiagnostics
  }
};
